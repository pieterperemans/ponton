export function matchRule(text: string, amount: number): string | undefined {
  const t = text.toUpperCase();
  for (const r of RULES) {
    if (r.sign === 'in' && amount <= 0) continue;
    if (r.sign === 'out' && amount >= 0) continue;
    if (r.re.test(t)) return r.cat;
  }
  return undefined;
}
